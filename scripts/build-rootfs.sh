#!/usr/bin/env bash
# SPDX-License-Identifier: Apache-2.0
#
# Assembles the partition contents with the Android style layout astraOS uses:
#
#   system.img   /  (system-as-root)
#                ├── system/{bin,lib,etc,app,priv-app,framework,fonts,media}
#                ├── bin -> system/bin   lib -> system/lib   etc -> system/etc
#                ├── usr -> system       var -> data/var     sdcard -> data/media/0
#                └── dev proc sys run tmp mnt data vendor product (mount points)
#   vendor.img   /vendor/{build.prop,etc/fstab,etc/init,firmware}
#   product.img  /product/{build.prop,app}
#   ramdisk      /init (static astra init, first stage) + /first_stage.fstab
#                + /bin/busybox (static, for the USB rescue shell)
source "$(dirname "$0")/common.sh"
need apk cpio gzip

[ -d "$OUT/astra-install/system" ] || die "astraOS is not built, run ./build.sh astra"
[ -d "$OUT/modules/lib/modules" ] || die "kernel modules missing, run ./build.sh kernel"

# ---- 1. Userland libraries from Alpine ---------------------------------------
log "rootfs: installing Alpine $ALPINE_BRANCH packages"
rm -rf "$STAGE"
mkdir -p "$STAGE/etc/apk"
printf '%s\n' "$ALPINE_MIRROR/$ALPINE_BRANCH/main" "$ALPINE_MIRROR/$ALPINE_BRANCH/community" > "$STAGE/etc/apk/repositories"
apk_root() { apk --root "$STAGE" --arch aarch64 --keys-dir /etc/apk/keys --no-progress "$@"; }
apk_root add --initdb --update-cache --quiet alpine-baselayout-data

required=() optional=()
while read -r line; do
    line=${line%%#*}
    line=$(echo "$line" | xargs)
    [ -z "$line" ] && continue
    if [[ $line == \?* ]]; then optional+=("${line#?}"); else required+=("$line"); fi
done < "$DEVICE_DIR/packages.txt"
apk_root add --quiet "${required[@]}"
for pkg in "${optional[@]}"; do
    apk_root add --quiet "$pkg" || warn "optional package $pkg not available"
done

# ---- 2. Relocate to the astraOS layout ---------------------------------------
log "rootfs: building the system partition"
rm -rf "$SYSTEM_ROOT"
mkdir -p "$SYSTEM_ROOT/system"/{bin,lib,etc}
cp -a "$STAGE/usr/." "$SYSTEM_ROOT/system/"
cp -a "$STAGE/lib/." "$SYSTEM_ROOT/system/lib/"
cp -a "$STAGE/bin/." "$SYSTEM_ROOT/system/bin/"
cp -a "$STAGE/sbin/." "$SYSTEM_ROOT/system/bin/"
if [ -d "$SYSTEM_ROOT/system/sbin" ]; then
    cp -a "$SYSTEM_ROOT/system/sbin/." "$SYSTEM_ROOT/system/bin/"
    rm -rf "$SYSTEM_ROOT/system/sbin"
fi
ln -s bin "$SYSTEM_ROOT/system/sbin"
cp -a "$STAGE/etc/." "$SYSTEM_ROOT/system/etc/"
# No package manager on the device: the system partition is read-only.
rm -rf "$SYSTEM_ROOT/system/lib/apk" "$SYSTEM_ROOT/system/etc/apk" "$SYSTEM_ROOT/system/share/apk"

# astraOS itself (overrides passwd, group, fonts.conf...). Replace what is
# there instead of writing into it: Alpine's /sbin/init is a link to
# /bin/busybox, and copying through it left /system/bin/init pointing at
# BusyBox (and overwrote the build machine's busybox).
cp -a --remove-destination "$OUT/astra-install/." "$SYSTEM_ROOT/"
[ -L "$SYSTEM_ROOT/system/bin/init" ] && die "/system/bin/init is a link, not astraOS init"
# Cloudy's engine (scripts/build-llama.sh)
[ -d "$OUT/llama-install" ] && cp -a --remove-destination "$OUT/llama-install/." "$SYSTEM_ROOT/"

# Kernel modules
mkdir -p "$SYSTEM_ROOT/system/lib/modules"
cp -a "$OUT/modules/lib/modules/." "$SYSTEM_ROOT/system/lib/modules/"
depmod -b "$SYSTEM_ROOT/system" "$(kernel_release)" 2>/dev/null || warn "depmod failed"

# Root of the filesystem
cd "$SYSTEM_ROOT"
mkdir -p dev proc sys run tmp mnt data vendor product metadata odm
ln -sfn system/bin bin
ln -sfn system/bin sbin
ln -sfn system/lib lib
ln -sfn system usr
ln -sfn system/etc etc
ln -sfn data/var var
ln -sfn data/media/0 sdcard
ln -sfn system/bin/init init
chmod 1777 tmp
# Resolver configuration is written at runtime (iwd -> openresolv, modem bearers).
ln -sfn /run/resolv.conf system/etc/resolv.conf
cd - >/dev/null

# ---- 3. Vendor ---------------------------------------------------------------
log "rootfs: building the vendor partition"
rm -rf "$VENDOR_ROOT"
mkdir -p "$VENDOR_ROOT"
cp -a "$DEVICE_DIR/rootdir/vendor/." "$VENDOR_ROOT/"
cat > "$VENDOR_ROOT/build.prop" <<EOF
# Generated by astra_device_xiaomi_sweet
ro.product.device=$DEVICE
ro.product.model=$DEVICE_MODEL
ro.product.brand=$DEVICE_BRAND
ro.product.manufacturer=$DEVICE_MANUFACTURER
ro.board.platform=$SOC
ro.astra.ui.scale=$UI_SCALE
ro.astra.motion_blur=${MOTION_BLUR:-true}
ro.kernel.release=$(kernel_release)
EOF
mkdir -p "$VENDOR_ROOT/firmware"
if [ -d "$SRC/firmware/usr/lib/firmware" ]; then
    cp -a "$SRC/firmware/usr/lib/firmware/." "$VENDOR_ROOT/firmware/"
    [ -d "$SRC/firmware/usr/share" ] && cp -a "$SRC/firmware/usr/share" "$VENDOR_ROOT/"
else
    warn "device firmware missing: GPU, audio and modem will not start"
fi

# ---- 4. Product --------------------------------------------------------------
rm -rf "$PRODUCT_ROOT"
mkdir -p "$PRODUCT_ROOT/app" "$PRODUCT_ROOT/etc/init" "$PRODUCT_ROOT/fonts"
echo "# product customisations for $DEVICE" > "$PRODUCT_ROOT/build.prop"

# ---- 5. Ramdisk (first stage init) -------------------------------------------
log "rootfs: building the ramdisk"
rm -rf "$RAMDISK"
mkdir -p "$RAMDISK"/{dev,proc,sys,newroot,bin}
cp "$OUT/astra-install/system/bin/init" "$RAMDISK/init"
# A static busybox lets the first stage offer a rescue shell over USB serial
# when it cannot boot (see core/init/rescue.c).
apk_root add --quiet busybox-static || warn "busybox-static not available: no rescue shell"
[ -x "$STAGE/bin/busybox.static" ] && cp "$STAGE/bin/busybox.static" "$RAMDISK/bin/busybox"
cp "$DEVICE_DIR/rootdir/vendor/etc/fstab" "$RAMDISK/first_stage.fstab"
# USB gadget modules for the rescue mode (logs drive and serial shell), when
# the kernel has the gadget stack as modules (postmarketOS's kernel).
mods=$OUT/modules/lib/modules/$(kernel_release)
mkdir -p "$RAMDISK/lib/modules"
: > "$RAMDISK/lib/modules/gadget.order"
for m in kernel/drivers/usb/gadget/libcomposite kernel/drivers/usb/gadget/function/u_serial \
         kernel/drivers/usb/gadget/function/usb_f_acm kernel/drivers/usb/gadget/function/usb_f_mass_storage; do
    for f in "$mods/$m".ko*; do
        [ -f "$f" ] || continue
        cp "$f" "$RAMDISK/lib/modules/"
        basename "$f" >> "$RAMDISK/lib/modules/gadget.order"
    done
done
(cd "$RAMDISK" && find . | LC_ALL=C sort | cpio -o -H newc -R 0:0 --quiet | gzip -9n) > "$OUT/ramdisk.cpio.gz"

log "rootfs: system $(du -sh "$SYSTEM_ROOT" | cut -f1), vendor $(du -sh "$VENDOR_ROOT" | cut -f1)"
