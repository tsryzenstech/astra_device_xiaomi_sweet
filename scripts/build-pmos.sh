#!/usr/bin/env bash
# SPDX-License-Identifier: Apache-2.0
#
# Builds the image flashed to userdata: postmarketOS (now named Nura) for
# SM7150 phones, installed with pmbootstrap the way postmarketOS installs
# itself, plus the astraos package (astraOS's system tree from the astra and
# llama steps, see pmos/astraos/).
#
# Runs on the build machine as your user: pmbootstrap asks for sudo itself
# and refuses to run as root. Its files live in PMB_HOME (a Linux
# filesystem: not /mnt/c on WSL).
source "$(dirname "$0")/common.sh"
need git python3 sudo openssl tar gzip ssh-keygen mcopy mdir debugfs dd

[ "$(id -u)" != 0 ] || die "pmos: run this step as your user, not root (pmbootstrap uses sudo itself)"
[ -d "$OUT/astra-install/system" ] || die "pmos: astraOS is not built, run ./build.sh astra"

PMB_HOME=${PMB_HOME:-$HOME/.local/share/astra-pmbootstrap}
PMB=$PMB_HOME/pmbootstrap
WORK=$PMB_HOME/work
CFG=$PMB_HOME/pmbootstrap.cfg
mkdir -p "$PMB_HOME"

log "pmos: pmbootstrap $PMB_REF"
git_fetch "$PMB_REPO" "$PMB_REF" "$PMB"
# Details go to $WORK/log.txt.
pmb() { python3 "$PMB/pmbootstrap.py" -c "$CFG" -w "$WORK" "$@"; }
pmb_value() { python3 "$PMB/pmbootstrap.py" -c "$CFG" -w "$WORK" -q config "$1"; }

# First run: pmbootstrap's own setup with its default answers (as its CI
# does), then the settings below.
if [ ! -f "$CFG" ]; then
    log "pmos: setting up pmbootstrap in $WORK"
    { yes '' || true; } | pmb init
fi

# The release channel is the checked out branch of pmaports.
aports=$(pmb_value aports)
if [ "$(git -C "$aports" rev-parse --abbrev-ref HEAD)" != "$PMOS_CHANNEL" ]; then
    log "pmos: postmarketOS $PMOS_CHANNEL"
    pmb shutdown
    git -C "$aports" fetch origin "$PMOS_CHANNEL"
    git -C "$aports" checkout -B "$PMOS_CHANNEL" "origin/$PMOS_CHANNEL"
    pmb -y zap
else
    git -C "$aports" pull --ff-only -q origin "$PMOS_CHANNEL" || warn "pmos: could not update pmaports"
fi

pmb config device "$PMOS_DEVICE"
pmb config ui none
pmb config service_manager openrc
pmb config hostname astra
pmb config extra_packages none
pmb config build_pkgs_on_install True
pmb config auto_zap_misconfigured_chroots silently

# ---- The astraos package -----------------------------------------------------
log "pmos: astraos package"
stage=$PMB_HOME/stage
tree=$stage/tree
rm -rf "$stage"
mkdir -p "$tree"
cp -a "$OUT/astra-install/." "$tree/"
[ -d "$OUT/llama-install" ] && cp -a "$OUT/llama-install/." "$tree/"

mkdir -p "$tree/vendor" "$tree/product/app" "$tree/data" "$tree/etc/runlevels/default"
cp -a "$DEVICE_DIR/rootdir/vendor/." "$tree/vendor/"
cat > "$tree/vendor/build.prop" <<EOF
# Generated by astra_device_xiaomi_sweet
ro.product.device=$DEVICE
ro.product.model=$DEVICE_MODEL
ro.product.brand=$DEVICE_BRAND
ro.product.manufacturer=$DEVICE_MANUFACTURER
ro.board.platform=$SOC
ro.astra.ui.scale=$UI_SCALE
ro.astra.motion_blur=${MOTION_BLUR:-true}
ro.astra.base=postmarketOS $PMOS_CHANNEL
EOF
echo "# product customisations for $DEVICE" > "$tree/product/build.prop"
# Services started at boot: astraOS and the daemons astrad drives (their
# OpenRC scripts come with the *-openrc packages). Links instead of
# rc-update in the post-install: they do not depend on install order.
for svc in astraos dbus iwd bluetooth modemmanager sshd; do
    ln -sfn "/etc/init.d/$svc" "$tree/etc/runlevels/default/$svc"
done
# SSH over the USB cable (root@172.16.42.1), only with this machine's key,
# for looking into a phone live (passwords are off: 50-astraos.sshd.conf).
# ASTRA_DEV_SSH=0 (GitHub builds) leaves the key out: nobody can log in.
if [ "${ASTRA_DEV_SSH:-1}" = 1 ]; then
    key=$PMB_HOME/ssh/astra_dev
    if [ ! -f "$key" ]; then
        mkdir -p "$(dirname "$key")"
        ssh-keygen -q -t ed25519 -N '' -C "astraOS dev ($(hostname))" -f "$key"
    fi
    install -d -m 700 "$tree/root/.ssh"
    install -m 600 "$key.pub" "$tree/root/.ssh/authorized_keys"
    log "pmos: SSH over USB: ssh -i $key root@172.16.42.1"
fi
# USB networking (postmarketOS's initramfs sets it up) with the Linux
# Foundation's IDs for a composite gadget: with Google's (18d1:d001, the
# default) Windows binds its Android ADB driver and the network never shows.
cat > "$tree/etc/deviceinfo" <<EOF
# astraOS: overrides of postmarketOS's deviceinfo for this phone
deviceinfo_usb_idVendor="0x1d6b"
deviceinfo_usb_idProduct="0x0104"
EOF
# astraOS's libraries (libastra) are in /system/lib.
printf '%s\n' /lib /usr/local/lib /usr/lib /system/lib > "$tree/etc/ld-musl-aarch64.path"
ln -sfn data/media/0 "$tree/sdcard"

version=$(sed -n 's/^ro.astra.version=//p' "$OUT/astra-install/system/build.prop" 2>/dev/null)
# apk versions have no "-rev3": the package is <version>_git<time>.
pkgver="${version%%-*}"
pkgver="${pkgver:-0.1}_git$(date -u +%Y%m%d%H%M%S)"
depends=$(sed 's/#.*//' "$DEVICE_DIR/pmos/depends.txt" | xargs)

aport=$aports/temp/astraos
rm -rf "$aport"
mkdir -p "$aport"
src=$DEVICE_DIR/pmos/astraos
cp "$src/astraos.initd" "$src/astraos.confd" "$src/astraos.post-install" "$src/60-astraos.rules" \
   "$src/50-astraos.sshd.conf" "$src"/plymouth/* "$aport/"
echo "$KERNEL_CMDLINE" > "$aport/90-astraos.conf"
sed -e "s|@VERSION@|$pkgver|" -e "s|@DEPENDS@|$depends|" "$src/APKBUILD.in" > "$aport/APKBUILD"
tar -C "$stage" --owner=0 --group=0 --numeric-owner -czf "$aport/astraos-tree.tar.gz" tree

pmb -y checksum astraos
pmb -y build --force --arch aarch64 astraos

# ---- Install -------------------------------------------------------------------
# The user account's password (pmbootstrap needs one; nothing logs in with it:
# SSH takes keys only, no login prompt) stays on the build machine.
pwfile=$PMB_HOME/password
[ -f "$pwfile" ] || (umask 077 && openssl rand -hex 12 > "$pwfile")
# pmbootstrap leaves its chroots, mounts and loop devices active after each
# command. Stale binds of the loop partitions (/dev/loop0p1, installp1) made
# an image whose boot partition was formatted but empty - nothing to start:
# begin from none.
pmb shutdown
log "pmos: installing postmarketOS $PMOS_CHANNEL ($PMOS_DEVICE) with astraOS"
pmb -y install --zap --password "$(cat "$pwfile")" --add astraos
pmb shutdown

# Where pmbootstrap install leaves the (raw) image.
mkdir -p "$OUT/pmos"
img=$WORK/chroot_native/home/pmos/rootfs/$PMOS_DEVICE.img
raw=$OUT/pmos/raw.img
[ -e "$img" ] || die "pmos: pmbootstrap did not produce $PMOS_DEVICE.img"
cp --sparse=always "$img" "$raw" 2>/dev/null ||
    { sudo cp --sparse=always "$img" "$raw" && sudo chown "$(id -u):$(id -g)" "$raw"; }

# The boot partition must hold what U-Boot starts: systemd-boot, the kernel,
# the initramfs and the boot entry. Copied in again (mtools, no mount) from
# the device's /boot when they are missing; the build fails if they still are.
export MTOOLS_SKIP_CHECK=1
fat="$raw@@$(python3 "$DEVICE_DIR/scripts/pmos-image.py" boot-offset "$raw")"
boot_ok() {
    local f
    for f in EFI/BOOT/BOOTAA64.EFI vmlinuz initramfs loader/entries/pmos.conf; do
        mdir -b -i "$fat" "::/$f" >/dev/null 2>&1 || { echo "$f"; return 1; }
    done
}
if missing=$(boot_ok); then
    log "pmos: boot partition complete"
else
    warn "pmos: $missing is missing from the boot partition: copying /boot into it"
    rootfs_boot=$WORK/chroot_rootfs_$PMOS_DEVICE/boot
    mcopy -s -o -i "$fat" "$rootfs_boot"/* ::/
    missing=$(boot_ok) || die "pmos: the boot partition is still missing $missing"
    log "pmos: boot partition repaired"
fi

# The root partition must hold the system. An image whose writes got lost
# has the filesystem's structure and little else (the phone then panics
# at switch_root: "Attempted to kill init! exitcode=0x7f00").
read -r root_off root_size < <(python3 "$DEVICE_DIR/scripts/pmos-image.py" part "$raw" 2)
rootimg=$PMB_HOME/root-check.img
dd if="$raw" of="$rootimg" bs=4M iflag=skip_bytes,count_bytes skip="$root_off" count="$root_size" conv=sparse status=none
for f in /usr/bin/busybox /usr/sbin/init /system/bin/init /system/bin/sysboard /etc/init.d/astraos; do
    debugfs -R "stat $f" "$rootimg" 2>/dev/null | grep -q -E 'Type: (regular|symlink)' ||
        { rm -f "$rootimg" "$raw"; die "pmos: $f is missing from the image's root partition (run ./build.sh pmos again)"; }
done
rm -f "$rootimg"
log "pmos: root partition complete"

# Sparse: fastboot sends a sparse image in chunks; a raw one of a few GB
# makes it run out of memory (std::bad_alloc on Windows).
python3 "$DEVICE_DIR/scripts/pmos-image.py" sparse "$raw" "$OUT/pmos/userdata.img"
rm -f "$raw"
echo "$pkgver" > "$OUT/pmos/version"
log "pmos: $OUT/pmos/userdata.img ($(du -h "$OUT/pmos/userdata.img" | cut -f1))"
